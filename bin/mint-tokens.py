#!/usr/bin/env python3
"""
Mint ~/arch-mcp-secrets/tokens.json with two distinct tokens.

Generates both tokens itself so they cannot be accidentally reused —
which is exactly the failure that made james-arch-collab vanish.

    python3 mint-tokens.py                 # create the file (refuses to clobber)
    python3 mint-tokens.py --force         # overwrite, keeping a .bak
    python3 mint-tokens.py --url rcp-dev   # print the connector URL for one profile

Run ON THE SERVER. Nothing is printed unless you ask for a URL.
"""

import json
import os
import secrets
import shutil
import sys

MAP = os.path.expanduser("~/arch-mcp-secrets/tokens.json")
BASE = "https://mcp.crockart.com.au"

# Profiles this script knows how to create from scratch. Any profile
# already present in the map is preserved whether or not it appears here —
# see mint(). Adding mcp-staging because it is now a standing profile, not
# a one-off.
PROFILES = [
    {
        "label": "arch-collab",
        "root": "/home/crockart/arch-collab-core",
        "lanes": {"metadata": "metadata", "site": "site"},
        "session_tools": True,
    },
    {
        "label": "rcp-dev",
        "root": "/home/crockart/public_html/rcp",
        "lanes": {"site": ""},
        "session_tools": False,
        "write_extensions": ["html", "css", "js", "json", "txt", "md",
                             "png", "jpg", "jpeg", "gif", "svg", "webp", "ico",
                             "woff", "woff2", "ttf", "pdf"],
    },
    {
        "label": "mcp-staging",
        "root": "/home/crockart/arch-mcp-staging",
        "lanes": {"site": ""},
        "session_tools": False,
        "write_extensions": ["php", "sh", "md", "txt", "json"],
    },
]


def show_url(label):
    with open(MAP) as fh:
        data = json.load(fh)
    for token, profile in data.items():
        if isinstance(profile, dict) and profile.get("label") == label:
            print("{}/t/{}/".format(BASE, token))
            return 0
    print("No profile labelled {!r}. Labels present: {}".format(
        label, [p.get("label") for p in data.values() if isinstance(p, dict)]))
    return 1


def mint(force):
    if os.path.exists(MAP) and not force:
        print("{} already exists. Re-run with --force to replace it "
              "(a .bak is kept).".format(MAP))
        return 1

    os.makedirs(os.path.dirname(MAP), exist_ok=True)
    os.chmod(os.path.dirname(MAP), 0o700)

    if os.path.exists(MAP):
        shutil.copy2(MAP, MAP + ".bak")
        os.chmod(MAP + ".bak", 0o600)
        print("Existing map backed up to {}.bak".format(MAP))

    # Preserve every profile already in the map.
    #
    # The first version of this script rebuilt the file from the PROFILES
    # list alone, so --force SILENTLY DELETED any profile added by hand —
    # it destroyed the live mcp-staging profile on 2026-09-01 while
    # cheerfully reporting "2 distinct tokens", which was true and
    # entirely failed to mention the third one it had dropped. Rotation
    # must never lose a profile.
    existing = {}
    if os.path.exists(MAP):
        try:
            with open(MAP) as fh:
                loaded = json.load(fh)
            existing = {v.get("label"): v for v in loaded.values() if isinstance(v, dict)}
        except Exception as e:                 # noqa: BLE001
            print("Refusing to rotate: cannot read existing map ({}).".format(e))
            print("Fix or remove it first — overwriting blindly would lose profiles.")
            return 1

    known = {p["label"]: p for p in PROFILES}
    # Existing wins on conflict: the live map is the source of truth for
    # anything already provisioned, including hand-edited roots and lanes.
    merged = dict(known)
    merged.update(existing)

    carried = sorted(set(existing) - set(known))
    if carried:
        print("Preserving profile(s) not in this script's list: {}".format(", ".join(carried)))

    out = {"__comment": "Generated by mint-tokens.py. Keep OUTSIDE the web root, mode 600."}
    for label in sorted(merged):
        profile = dict(merged[label])
        profile.pop("_token", None)
        token = secrets.token_hex(32)          # 64 hex chars
        while token in out:                    # cannot happen; asserted anyway
            token = secrets.token_hex(32)
        out[token] = profile

    # Write with a tight umask so the secret is never briefly world-readable.
    old = os.umask(0o077)
    try:
        with open(MAP, "w") as fh:
            json.dump(out, fh, indent=2)
            fh.write("\n")
    finally:
        os.umask(old)
    os.chmod(MAP, 0o600)

    tokens = [k for k in out if k != "__comment"]
    assert len(set(tokens)) == len(tokens) == len(merged)

    print("Wrote {} (mode 600) with {} distinct tokens:".format(MAP, len(tokens)))
    for label in sorted(merged):
        note = "" if label in known else "   (preserved, not in script list)"
        print("  - {}{}".format(label, note))
    print("\nEVERY connector using any of these must be re-registered.")
    print("\nNext:")
    print("  python3 check-tokens.py")
    print("  python3 verify-lanes.py")
    print("  python3 mint-tokens.py --url rcp-dev     # when you need the connector URL")
    return 0


if __name__ == "__main__":
    args = sys.argv[1:]
    if "--url" in args:
        sys.exit(show_url(args[args.index("--url") + 1]))
    sys.exit(mint("--force" in args))

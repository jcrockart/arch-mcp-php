<?php
// Offline proof of the database entry in arch_project_info (ProjectDatabase):
// the engine and the SQLite file's place inside the project folder, read from
// config.php as text and never run, no absolute path and no connection setting
// ever returned, and an honest null with a note whenever it cannot tell.
// Temp directories only, no network, no git.
//
//     php tests/unit/test-project-database.php
$ROOT = __DIR__;
while (!is_file($ROOT.'/src/ProjectDatabase.php') && \dirname($ROOT) !== $ROOT) {
    $ROOT = \dirname($ROOT);
}
if (!is_file($ROOT.'/src/ProjectDatabase.php')) {
    fwrite(STDERR, "Cannot locate app root from ".__DIR__."\n");
    exit(2);
}
require $ROOT.'/src/ProjectDatabase.php';
require $ROOT.'/src/ProjectInfo.php';

use ArchMcp\ProjectDatabase;
use ArchMcp\ProjectInfo;

$pass = 0; $fail = 0;
function check(string $what, bool $ok): void {
    global $pass, $fail;
    $ok ? $pass++ : $fail++;
    printf("  [%s] %s\n", $ok ? 'PASS' : 'FAIL', $what);
}

$base = realpath(sys_get_temp_dir()) . '/archdb' . getmypid();
mkdir($base, 0775, true);
$base = realpath($base);
$n = 0;
/** A checkout directory whose config.php has the given body (after the opening tag). */
function checkout(string $body): string {
    global $base, $n;
    $d = $base.'/c'.(++$n);
    mkdir($d, 0775, true);
    file_put_contents($d.'/config.php', "<?php\n".$body);

    return $d;
}

echo "sqlite, as provisioning writes it\n";
$d = checkout("// Auto-generated by arch-portal's database provisioning.\ndeclare(strict_types=1);\n\ndefine('DB_ENGINE', 'sqlite');\ndefine('DB_PATH', '".'%ROOT%'."/data/app.sqlite');\n");
file_put_contents($d.'/config.php', str_replace('%ROOT%', $d, (string) file_get_contents($d.'/config.php')));
$r = ProjectDatabase::forCheckout($d);
check('engine and the path relative to the checkout', 'sqlite' === $r['engine'] && 'data/app.sqlite' === $r['file']);
check('the file is not there yet: exists false', false === $r['exists']);
mkdir($d.'/data', 0775, true);
file_put_contents($d.'/data/app.sqlite', '');
$r = ProjectDatabase::forCheckout($d);
check('once it is there: exists true', true === $r['exists'] && 'data/app.sqlite' === $r['file']);
check('says where the settings live', 'config.php' === $r['settings_file']);
check('no absolute path anywhere in the entry', !str_contains(json_encode($r, JSON_UNESCAPED_SLASHES), $base) && !str_contains(json_encode($r, JSON_UNESCAPED_SLASHES), '/tmp') && !str_contains(json_encode($r, JSON_UNESCAPED_SLASHES), '/home'));

echo "\nsqlite, other ways of writing the path\n";
$d = checkout("define('DB_ENGINE', 'sqlite');\ndefine('DB_PATH', __DIR__ . '/data/x.sqlite');\n");
check('__DIR__ plus a quoted string', 'data/x.sqlite' === ProjectDatabase::forCheckout($d)['file']);
$d = checkout("define(\"DB_ENGINE\", \"sqlite\");\ndefine(\"DB_PATH\", __DIR__.\"/db/y.sqlite\");\n");
check('double quotes and no spaces', 'db/y.sqlite' === ProjectDatabase::forCheckout($d)['file']);
$d = checkout("define('DB_ENGINE','sqlite');define('DB_PATH','".'%ROOT%'."/z.sqlite');\n");
file_put_contents($d.'/config.php', str_replace('%ROOT%', $d, (string) file_get_contents($d.'/config.php')));
check('a file directly in the project folder', 'z.sqlite' === ProjectDatabase::forCheckout($d)['file']);
$d = checkout("    define('DB_ENGINE', 'sqlite');\n    define('DB_PATH', __DIR__ . '/data/ind.sqlite');\n");
check('indented defines are found', 'data/ind.sqlite' === ProjectDatabase::forCheckout($d)['file']);

echo "\nsqlite, refused rather than guessed\n";
$d = checkout("define('DB_ENGINE', 'sqlite');\ndefine('DB_PATH', '/var/lib/elsewhere/app.sqlite');\n");
$r = ProjectDatabase::forCheckout($d);
check('outside the project folder: no file, a note, and the path is not leaked', null === $r['file'] && str_contains($r['note'], 'outside the project folder') && !str_contains(json_encode($r), 'elsewhere') && false === $r['exists']);
$d = checkout("define('DB_ENGINE', 'sqlite');\ndefine('DB_PATH', __DIR__ . '/../x.sqlite');\n");
$r = ProjectDatabase::forCheckout($d);
check('a path that climbs out with ..: no file and a note', null === $r['file'] && isset($r['note']));
$d = checkout("define('DB_ENGINE', 'sqlite');\ndefine('DB_PATH', __DIR__ . '/data/../../x.sqlite');\n");
check('a climb hidden behind a folder name is caught too', null === ProjectDatabase::forCheckout($d)['file']);
foreach ([
    "define('DB_PATH', getenv('APP_DB'));",
    "define('DB_PATH', dirname(__DIR__) . '/x.sqlite');",
    "define('DB_PATH', \$root . '/x.sqlite');",
    "define('DB_PATH', \"{\$root}/x.sqlite\");",
    "define('DB_PATH', __DIR__ . '/a' . '/b.sqlite');",
] as $line) {
    $d = checkout("define('DB_ENGINE', 'sqlite');\n".$line."\n");
    $r = ProjectDatabase::forCheckout($d);
    check('not a plain string, so not shown: '.substr($line, 0, 44), 'sqlite' === $r['engine'] && null === $r['file'] && str_contains($r['note'], 'cannot be read safely'));
}
$d = checkout("define('DB_ENGINE', 'sqlite');\n");
$r = ProjectDatabase::forCheckout($d);
check('sqlite with no DB_PATH: engine, no file, a note', 'sqlite' === $r['engine'] && null === $r['file'] && str_contains($r['note'], 'no DB_PATH'));

$d = checkout("const DB_ENGINE = 'sqlite';\nconst DB_PATH = __DIR__ . '/data/k.sqlite';\n");
$r = ProjectDatabase::forCheckout($d);
check('const instead of define(): not guessed as mysql, engine not shown', null === $r['engine'] && null === $r['file'] && str_contains($r['note'], 'cannot be read safely'));
$d = checkout("define('DB_ENGINE', 'sqlite');\nconst DB_PATH = __DIR__ . '/data/k.sqlite';\n");
$r = ProjectDatabase::forCheckout($d);
check('sqlite engine but DB_PATH as a const: says it cannot read it, not "no DB_PATH"', 'sqlite' === $r['engine'] && null === $r['file'] && str_contains($r['note'], 'cannot be read safely') && !str_contains($r['note'], 'defines no DB_PATH'));
$d = checkout("define('DB_ENGINE', 'mysql'); // define('DB_ENGINE', 'sqlite');\n");
check('a define after a trailing comment on the same line is not picked up', 'mysql' === ProjectDatabase::forCheckout($d)['engine']);

echo "\nmysql: the engine and nothing else\n";
$d = checkout("define('DB_ENGINE', 'mysql');\ndefine('DB_HOST', 'db.internal.example');\ndefine('DB_NAME', 'appdb');\ndefine('DB_USER', 'appuser');\ndefine('DB_PASS', 'sup3rsecret!');\n");
$r = ProjectDatabase::forCheckout($d);
$j = json_encode($r);
check('engine mysql, no file', 'mysql' === $r['engine'] && null === $r['file'] && null === $r['exists']);
check('no host, name, user or password anywhere in the entry', !str_contains($j, 'sup3rsecret') && !str_contains($j, 'db.internal') && !str_contains($j, 'appuser') && !str_contains($j, 'appdb') && !str_contains($j, 'DB_PASS'));
$d = checkout("define('DB_HOST', 'h');\ndefine('DB_NAME', 'n');\ndefine('DB_USER', 'u');\ndefine('DB_PASS', 'pw-not-shown');\n");
$r = ProjectDatabase::forCheckout($d);
check('no DB_ENGINE at all: mysql, the same assumption the database tools make', 'mysql' === $r['engine'] && !str_contains(json_encode($r), 'pw-not-shown'));

echo "\nunreadable engine, missing or odd config\n";
$d = checkout("define('DB_ENGINE', getenv('ENGINE'));\n");
$r = ProjectDatabase::forCheckout($d);
check('an engine that is not a plain string: null and a note', null === $r['engine'] && str_contains($r['note'], 'cannot be read safely'));
$d = checkout("define('DB_ENGINE', 'SQLite; DROP');\n");
check('an engine value that is not a plain word is refused', null === ProjectDatabase::forCheckout($d)['engine']);
$d = checkout("// define('DB_ENGINE', 'mysql');\n# define('DB_ENGINE', 'mysql');\ndefine('DB_ENGINE', 'sqlite');\ndefine('DB_PATH', __DIR__ . '/data/c.sqlite');\n");
check('commented-out defines are ignored', 'sqlite' === ProjectDatabase::forCheckout($d)['engine'] && 'data/c.sqlite' === ProjectDatabase::forCheckout($d)['file']);
mkdir($base.'/none', 0775, true);
$r = ProjectDatabase::forCheckout($base.'/none');
check('no config.php: nulls and a note, no path in it', null === $r['engine'] && null === $r['file'] && str_contains($r['note'], 'no config.php') && !str_contains(json_encode($r, JSON_UNESCAPED_SLASHES), $base));
check('empty directory name: nulls and a note', null === ProjectDatabase::forCheckout('')['engine']);

echo "\nconfig.php is read, never run\n";
$marker = $base.'/ran-marker';
$d = checkout("file_put_contents('".$marker."', 'ran');\ndefine('DB_ENGINE', 'sqlite');\ndefine('DB_PATH', __DIR__ . '/data/m.sqlite');\n");
$r = ProjectDatabase::forCheckout($d);
check('its code did not execute', !is_file($marker));
check('and the entry is still right', 'data/m.sqlite' === $r['file']);
check('the process has no DB constants defined by this read', !\defined('DB_ENGINE') && !\defined('DB_PATH') && !\defined('DB_PASS'));

echo "\nProjectInfo::describe(): one entry per environment\n";
$stg = checkout("define('DB_ENGINE', 'sqlite');\ndefine('DB_PATH', __DIR__ . '/data/stg.sqlite');\n");
$prd = checkout("define('DB_ENGINE', 'mysql');\ndefine('DB_HOST', 'prodhost.example');\ndefine('DB_PASS', 'prod-secret-pw');\n");
$p = static fn (string $root): array => [
    'label' => 'p', 'root' => $root, 'lanes' => ['code' => '', 'core' => ''], 'session_tools' => true, 'write_extensions' => ['php'],
    'pull_allowed' => false, 'pull_branch' => 'main', 'push_allowed' => false, 'push_branch' => 'main',
    'db_apply_allowed' => false, 'dependency_manager' => 'none', 'profile_environment' => 'staging',
];
$r = ProjectInfo::describe('demo', 'production', $p($stg), $p($prd));
check('staging view carries its own sqlite entry', 'sqlite' === $r['staging']['database']['engine'] && 'data/stg.sqlite' === $r['staging']['database']['file']);
check('production view carries its own entry, engine only', 'mysql' === $r['production']['database']['engine'] && null === $r['production']['database']['file']);
check('no secret, host or absolute path in the whole reply', !str_contains(json_encode($r), 'prod-secret-pw') && !str_contains(json_encode($r), 'prodhost.example') && !str_contains(json_encode($r, JSON_UNESCAPED_SLASHES), $base));
$r = ProjectInfo::describe('demo', 'production', $p($base.'/none'), null);
check('a checkout with no config.php still answers', true === $r['success'] && null === $r['staging']['database']['engine']);

exec('rm -rf '.escapeshellarg($base));
printf("\n%d passed, %d failed\n", $pass, $fail);
exit($fail > 0 ? 1 : 0);
